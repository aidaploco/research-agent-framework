#!/usr/bin/env python3
"""Summarize the reference runs from their traces into outputs/SUMMARY.md.

    uv run python scripts/summarize_reference.py

Reads outputs/traces/<mode>/ for both modes (written by scripts/run_reference.py) and prints a
markdown table, one row per question per mode, so the README's numbers come from the traces and
are not copied by hand.
"""

import sys
from pathlib import Path

from research_agent.reference import REFERENCE_QUESTIONS
from research_agent.tracing import SynthesisStep, ToolStep, Trace, TraceStore

OUT = Path(__file__).resolve().parent.parent / "outputs"
MODES = ("single-pass", "multi-step")


def latest_by_question(mode: str) -> dict[str, Trace]:
    store = TraceStore(OUT / "traces" / mode)
    traces: dict[str, Trace] = {}
    for f in sorted(store.dir.glob("*.json")):  # ids sort in time order: the last one wins
        t = Trace.model_validate_json(f.read_text())
        traces[t.question] = t
    return traces


def row(n: int, mode: str, t: Trace | None) -> str:
    if t is None:
        return f"| Q{n} | {mode} | (not run) | | | | | |"
    tools = [s for s in t.steps if isinstance(s, ToolStep) and s.status != "skipped"]
    synth = next((s for s in t.steps if isinstance(s, SynthesisStep)), None)
    calls = [a for s in t.steps for a in getattr(s, "llm_attempts", [])]
    tokens = sum(a.prompt_tokens + a.completion_tokens for a in calls)
    used = ", ".join(dict.fromkeys(s.tool for s in tools)) or "none"
    claims = f"{len(synth.sourced)} / {len(synth.unverified)}" if synth else "n/a"
    waited = sum(a.waited_ms for a in calls) / 1000
    return (
        f"| Q{n} | {mode} | {t.outcome} | {len(tools)} ({used}) | {claims} | {tokens:,} | "
        f"{waited:.0f} s | {t.duration_ms / 1000:.0f} s |"
    )


def main() -> None:
    by_mode = {m: latest_by_question(m) for m in MODES}
    lines = [
        "| Q | Mode | Outcome | Tool calls | Sourced / unverified claims | Tokens | Waiting | Time |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for n, _kind, question in REFERENCE_QUESTIONS:
        for mode in MODES:
            lines.append(row(n, mode, by_mode[mode].get(question)))
    table = "\n".join(lines)
    (OUT / "SUMMARY.md").write_text(
        "# Reference runs: single-pass vs multi-step\n\n"
        "Generated by `scripts/summarize_reference.py` from the traces in `outputs/traces/`. "
        "One live run per question per mode on one day; not a benchmark. Tokens are prompt plus "
        "output; waiting is time spent waiting for the free tier's token allowance.\n\n"
        f"{table}\n"
    )
    print(table, file=sys.stdout)


if __name__ == "__main__":
    main()
